#ifndef ANALOGSOLVER_H
#define ANALOGSOLVER_H

#include <QString>

class CircuitScene;

// حل‌کننده تحلیل مدار آنالوگ DC (خطی) با روش Modified Nodal Analysis (MNA).
//
// دامنه این نسخه (عمداً محدود - طبق یادداشت HANDOFF قبل از این فاز):
//   - قطعات پشتیبانی‌شده: Resistor (خطی، ویژگی "resistance")، DC Source (منبع
//     ولتاژ ایده‌آل، ویژگی "voltage")، Ground (مرجع صفر ولت)، و AnalogVoltmeter/
//     AnalogAmmeter (به measurementtools.h مراجعه کن).
//   - پشتیبانی نمی‌شود (فازهای بعدی، عمداً خارج از این فاز نگه داشته شده):
//     خازن/سلف (نیاز به گسسته‌سازی زمانی - مدار دیفرانسیلی)، دیود/ترانزیستور
//     (غیرخطی - نیاز به تکرار نیوتن-رافسون)، Battery (این قطعه هنوز اصلاً در
//     پروژه پیاده نشده)، رفتار آنالوگ Switch/PushButton (باز=مدار باز،
//     بسته=اتصال کوتاه - این دو فعلاً فقط دیجیتالی‌اند).
//   - این حل‌کننده کاملاً مستقل و اضافه‌ای به سیستم دیجیتال موجود (LogicValue
//     روی Pin/Node) است: قطعات آنالوگ پایه‌هایشان Bidirectional هستند (پیش‌فرض
//     Pin) و اصلاً در Node::resolvedValue() دیجیتال شرکت نمی‌کنند - پس این دو
//     سیستم هرگز با هم تداخل ندارند، حتی وقتی هر دو نوع قطعه روی یک صحنه باشند.
//
// یک بوم می‌تواند شامل چند زیرمدار جدا از هم باشد (چند شبکه غیرمتصل)؛ هرکدام
// جداگانه (با Union-Find روی گراف مقاومت/منبع) شناسایی و حل می‌شود. زیرمداری
// که هیچ Ground ای نداشته باشد قابل حل نیست - دقیقاً طبق بند ۶.۱ سند پروژه که
// وجود حداقل یک GND را برای شبیه‌سازی الزامی می‌داند؛ گره‌های آن زیرمدار
// hasVoltage()==false باقی می‌مانند (نه صفر، نه مقدار کهنه‌ی تیک قبلی).
class AnalogSolver
{
public:
    // مدار داخل scene را تحلیل می‌کند و نتیجه را روی Node::setVoltage() (و برای
    // AnalogAmmeter ها روی خودِ قطعه با setMeasuredCurrent()) ذخیره می‌کند.
    // اگر هیچ عنصر آنالوگی (مقاومت/منبع) در مدار نبود، این یک خطا نیست - true
    // برمی‌گرداند بدون کاری کردن (یعنی مدار کاملاً دیجیتالی است، طبیعی است).
    // اگر حداقل یک زیرمدار آنالوگ بود ولی به دلیل نبود Ground یا معادلات
    // ناسازگار/تکین قابل حل نبود، false برمی‌گرداند و errorMessage (اختیاری)
    // را با شرح موضوع پر می‌کند - این پیام برای گزارش به SimulationLogger است.
    static bool solve(CircuitScene *scene, QString *errorMessage = nullptr);
};

#endif // ANALOGSOLVER_H
